export function publishedProjects(items) {
  return items.filter(p => p.published !== false).slice().sort((a, b) => a.order - b.order);
}
export function resolveHomeSections(items, config = homeSections) {
  const published = publishedProjects(items);
  return config.filter(s => s.visible).slice().sort((a, b) => a.order - b.order)
    .map(s => ({ ...s, projects: published.filter(p => p.category === s.category && (!s.featuredOnly || p.featured)) }));
}
export function nextPublishedProject(project, items) {
  const published = publishedProjects(items);
  return published.find(p => p.slug === project.nextProject && p.id !== project.id)
    || published[(published.findIndex(p => p.id === project.id) + 1) % published.length];
}
